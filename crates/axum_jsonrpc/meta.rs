use std::marker::PhantomData;

use schemars::JsonSchema;
use serde_json::Value;

/// Runtime metadata captured at method registration.
#[derive(Debug, Clone)]
pub struct MethodMeta {
    pub name: String,
    pub summary: Option<String>,
    pub description: Option<String>,
    pub tags: Vec<String>,
    pub deprecated: bool,
    pub params_schema: Option<Value>,
    pub result_schema: Option<Value>,
}

impl MethodMeta {
    pub fn new(name: impl Into<String>) -> Self {
        let name = name.into();
        let tags = default_tag(&name).into_iter().collect();
        Self {
            name,
            summary: None,
            description: None,
            tags,
            deprecated: false,
            params_schema: None,
            result_schema: None,
        }
    }
}

fn default_tag(name: &str) -> Option<String> {
    name.split('.')
        .next()
        .filter(|s| !s.is_empty())
        .map(str::to_string)
}

/// Something that can be passed to [`crate::RpcRouter::register`] without calling a helper.
///
/// Generated by `#[rpc]` as a unit struct, e.g. `detail_account_rpc`.
pub trait Registrable<S = ()> {
    fn register(
        self,
        router: crate::RpcRouter<S>,
    ) -> Result<crate::RpcRouter<S>, crate::RegisterError>;
}

/// Registration unit: handler + OpenRPC meta (single source for router + docs).
pub struct MethodSpec<H, T> {
    pub(crate) name: String,
    pub(crate) handler: H,
    pub(crate) meta: MethodMeta,
    pub(crate) _marker: PhantomData<fn() -> T>,
}

impl<H, T, S> Registrable<S> for MethodSpec<H, T>
where
    S: Clone + Send + Sync + 'static,
    H: super::handler::RpcHandler<T, S> + Send + Sync + 'static,
    T: 'static,
{
    fn register(
        self,
        router: crate::RpcRouter<S>,
    ) -> Result<crate::RpcRouter<S>, crate::RegisterError> {
        router.register_spec(self)
    }
}

impl<H, T> MethodSpec<H, T> {
    pub fn new(name: impl Into<String>, handler: H) -> Self {
        let name = name.into();
        let meta = MethodMeta::new(name.clone());
        Self {
            name,
            handler,
            meta,
            _marker: PhantomData,
        }
    }

    pub fn summary(mut self, summary: impl Into<String>) -> Self {
        self.meta.summary = Some(summary.into());
        self
    }

    pub fn description(mut self, description: impl Into<String>) -> Self {
        self.meta.description = Some(description.into());
        self
    }

    pub fn tag(mut self, tag: impl Into<String>) -> Self {
        self.meta.tags = vec![tag.into()];
        self
    }

    pub fn deprecated(mut self, deprecated: bool) -> Self {
        self.meta.deprecated = deprecated;
        self
    }

    pub fn params<P: JsonSchema>(mut self) -> Self {
        self.meta.params_schema = Some(json_schema::<P>());
        self
    }

    pub fn result<R: JsonSchema>(mut self) -> Self {
        self.meta.result_schema = Some(json_schema::<R>());
        self
    }
}

pub(crate) fn json_schema<T: JsonSchema>() -> Value {
    schemars::schema_for!(T).to_value()
}
