//! Tiny string builder + shared codegen helpers.

use crate::model::{Ir, Method, Model};
use std::fmt::Write as _;

#[derive(Default)]
pub struct SourceBuf(String);

impl SourceBuf {
    pub fn line(&mut self, s: impl AsRef<str>) {
        let _ = writeln!(self.0, "{}", s.as_ref());
    }

    pub fn blank(&mut self) {
        self.0.push('\n');
    }

    pub fn into_string(self) -> String {
        self.0
    }
}

macro_rules! w {
    ($buf:expr, $($t:tt)*) => {{
        $buf.line(format!($($t)*));
    }};
}

pub(crate) use w;

#[derive(Clone, Copy)]
pub enum DocStyle {
    /// Swift / Dart `///`
    TripleSlash,
    /// Kotlin / TS `/** … */`
    Block,
}

pub fn banner(o: &mut SourceBuf, ir: &Ir) {
    w!(o, "// Code generated by gen_mobile_clients — DO NOT EDIT.");
    w!(o, "// Source: OpenRPC {} {}", ir.title, ir.version);
}

/// Emit a doc comment from OpenRPC `description` / summary. No-op if blank.
pub fn doc_comment(o: &mut SourceBuf, text: &str, style: DocStyle, indent: &str) {
    let lines: Vec<&str> = text
        .lines()
        .map(str::trim)
        .filter(|l| !l.is_empty())
        .collect();
    if lines.is_empty() {
        return;
    }
    match style {
        DocStyle::TripleSlash => {
            for line in lines {
                w!(o, "{indent}/// {line}");
            }
        }
        DocStyle::Block => {
            if let [line] = lines.as_slice() {
                w!(o, "{indent}/** {line} */");
            } else {
                w!(o, "{indent}/**");
                for line in lines {
                    w!(o, "{indent} * {line}");
                }
                w!(o, "{indent} */");
            }
        }
    }
}

pub fn rpc_docs(o: &mut SourceBuf, m: &Method, style: DocStyle, indent: &str) {
    let summary = m.summary_one_line();
    let rpc = format!("RPC `{}`{}", m.name, m.auth_doc_suffix());
    let text = if summary.is_empty() {
        rpc
    } else {
        format!("{summary}\n{rpc}")
    };
    doc_comment(o, &text, style, indent);
}

/// Emit model description, then `emit`, then a blank line.
pub fn each_model(
    o: &mut SourceBuf,
    models: &[Model],
    style: DocStyle,
    mut emit: impl FnMut(&mut SourceBuf, &Model),
) {
    for model in models {
        doc_comment(o, &model.description, style, "");
        emit(o, model);
        o.blank();
    }
}

/// Run `emit` for each method after writing shared RPC docs.
pub fn each_method(
    o: &mut SourceBuf,
    methods: &[Method],
    style: DocStyle,
    indent: &str,
    mut emit: impl FnMut(&mut SourceBuf, &Method),
) {
    for m in methods {
        rpc_docs(o, m, style, indent);
        emit(o, m);
        o.blank();
    }
}
